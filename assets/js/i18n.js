var currentLang = localStorage.getItem('frontend_lang') || 'en';

function t(path) {
    var keys = path.split('.');
    var obj = i18nData[currentLang] || i18nData.en;
    for (var i = 0; i < keys.length; i++) {
        if (obj && obj[keys[i]] !== undefined) {
            obj = obj[keys[i]];
        } else {
            // Fallback to English
            obj = i18nData.en;
            for (var j = 0; j < keys.length; j++) {
                if (obj && obj[keys[j]] !== undefined) {
                    obj = obj[keys[j]];
                } else {
                    return path;
                }
            }
            return obj;
        }
    }
    return obj;
}

function switchLang(lang) {
    if (lang === currentLang) return;
    currentLang = lang;
    localStorage.setItem('frontend_lang', lang);
    applyTranslations();
}

function applyTranslations() {
    // Update all data-lang elements
    document.querySelectorAll('[data-lang]').forEach(function(el) {
        var key = el.getAttribute('data-lang');
        var text = t(key);
        if (text && text !== key) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = text;
            } else {
                el.innerHTML = text;
            }
        }
    });

    // Update lang switcher buttons in nav
    updateLangSwitcher();
}

function updateLangSwitcher() {
    var langBtns = document.querySelectorAll('.lang-switch-btn');
    langBtns.forEach(function(btn) {
        btn.classList.remove('active');
    });
    var activeBtn = document.querySelector('.lang-switch-btn[data-lang-target="' + currentLang + '"]');
    if (activeBtn) {
        activeBtn.classList.add('active');
    }
}

document.addEventListener('DOMContentLoaded', function() {
    applyTranslations();
});